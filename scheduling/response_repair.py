"""Daily repair of declined visits using the existing weekly constraint model."""

from collections import Counter
from dataclasses import replace

from config import SOLVER_SETTINGS, SolverSettings
from scheduling.cp_sat_scheduler import generate_weekly_schedule
from scheduling.types import ScheduleResult, ScheduledAppointment, SchedulingProblem


def fill_released_openings(
    problem: SchedulingProblem,
    released: list[ScheduledAppointment],
    settings: SolverSettings = SOLVER_SETTINGS,
) -> ScheduleResult:
    """Propose new visits only in released therapist/therapy/branch/time openings.

    The full week's pinned visits still count toward each therapy's weekly target.
    No future appointment is generated by this repair pass.
    """
    openings = {
        (item.therapist_id, item.department_id, item.location_id, item.date, item.slot_index)
        for item in released
    }
    return generate_weekly_schedule(
        replace(problem, new_booking_slots=openings), settings=settings,
    )


def suggest_declined_visits(
    problem: SchedulingProblem,
    released: list[ScheduledAppointment],
    settings: SolverSettings = SOLVER_SETTINGS,
) -> ScheduleResult:
    """Find unsaved alternatives within this week, limited to released demand."""
    pinned_counts = Counter(item.requirement_id for item in problem.pinned)
    released_counts = Counter(item.requirement_id for item in released)
    requirements = [
        replace(item, sessions_per_week=min(
            item.sessions_per_week,
            pinned_counts[item.id] + released_counts[item.id],
        ))
        for item in problem.requirements
    ]
    return generate_weekly_schedule(
        replace(
            problem, requirements=requirements, new_booking_slots=None,
            priority_requirement_ids=set(released_counts),
        ),
        settings=settings,
    )
