from datetime import date, datetime
from types import SimpleNamespace

from database.models import AppointmentStatus
from web_app import creator_appointment_fields, creator_plan_detail_fields


class AppointmentRow:
    """Minimal row shape returned by the appointment export query."""

    def __init__(self) -> None:
        self.appointment = SimpleNamespace(
            id=42,
            date=date(2026, 9, 21),
            slot_index=7,
            treatment_requirement_id=18,
            status=AppointmentStatus.PROPOSED,
        )
        self.patient_code = "P-100"
        self.patient_name = "Asha Kumar"
        self.therapist_name = "Dr. Patel"
        self.department_name = "Speech Therapy"
        self.location_name = "Kochi"

    def __getitem__(self, index: int):
        if index == 0:
            return self.appointment
        raise IndexError(index)


def test_creator_fields_match_flat_therapy_scheduler_form():
    fields = creator_appointment_fields(AppointmentRow())

    assert fields == {
        "Appointment_ID": 42,
        "Patient": "Asha Kumar",
        "Therapist": "Dr. Patel",
        "Therapy_Type": "Speech Therapy",
        "Branch": "Kochi",
        "Therapy_Plan": "P-100 - Speech Therapy - Plan 18",
        "Appointment_Date": "21-Sep-2026",
        "Start": "14:35:00",
        "End_Time": "15:15:00",
        "Duration_Minutes": 40,
        "Status": "Scheduled",
        "Notes": "Generated by Therapy Scheduler. Local appointment #42.",
    }


def test_creator_plan_detail_fields_normalize_report_link_names():
    fields = creator_plan_detail_fields({
        "ID": "491610000000026164",
        "Registration_Id": "FAKE-US-050",
        "Name": "Ryan Howard",
        "Branch": "Seattle Clinic",
        "Therapy_Type": "Special Education",
        "Specialty": "Special Education / IEP",
        "Weekly_Frequency": 2,
        "Duration_Months": 6,
        "Therapist": "Alexis Grant, M.Ed.",
        "Start_Date": "10-Oct-2026",
        "Plan_Added_Time": "14-Sep-2026 13:00:00",
        "Status": "Active",
    })

    assert fields == {
        "creator_record_id": "491610000000026164",
        "registration_id": "FAKE-US-050",
        "name": "Ryan Howard",
        "branch": "Seattle Clinic",
        "therapy_type": "Special Education",
        "specialty": "Special Education / IEP",
        "weekly_frequency": "2",
        "duration_months": "6",
        "therapist": "Alexis Grant, M.Ed.",
        "start_date": date(2026, 10, 10),
        "plan_added_time": datetime(2026, 9, 14, 13),
        "status": "Active",
    }
